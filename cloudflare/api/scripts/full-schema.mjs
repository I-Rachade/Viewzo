// Turns the whole backend schema (PostgreSQL) into a SQLite schema for D1,
// with the same rules as prisma/schema.prisma of the probe:
// - lists (String[], enum[]) become JSON text with "[]" as default,
// - @db.* column types are dropped (SQLite has none),
// - the datasource is sqlite and the client is built for Workers.
// Output: build/full/schema.prisma. CI then checks that Prisma accepts it and
// that the SQL it produces runs on a local D1.
//
//   node scripts/full-schema.mjs
import { mkdirSync, readFileSync, writeFileSync } from "node:fs";
import { dirname, resolve } from "node:path";
import { fileURLToPath } from "node:url";
import { BACKEND_SCHEMA, parseSchema } from "./schema-lib.mjs";

const here = dirname(fileURLToPath(import.meta.url));
const out = resolve(here, "../build/full/schema.prisma");

export function toSqlite(text) {
  const { enums } = parseSchema(text);
  let lists = 0;
  const body = text
    .replace(/generator client \{[\s\S]*?\}/, `generator client {\n  provider = "prisma-client"\n  output   = "./generated"\n  runtime  = "cloudflare"\n}`)
    .replace(/datasource db \{[\s\S]*?\}/, `datasource db {\n  provider = "sqlite"\n}`)
    .split(/\r?\n/)
    .map((line) => {
      const m = line.match(/^(\s+)(\w+)(\s+)(\w+)\[\](\s*)(.*)$/);
      if (!m) return line.replace(/\s@db\.\w+(\([^)]*\))?/g, "");
      const [, indent, field, gap, type, , rest] = m;
      if (type !== "String" && !enums.has(type)) return line; // relation list
      lists++;
      const attrs = rest.replace(/@default\(\[[^\]]*\]\)/, "").trim();
      return `${indent}${field}${gap}String @default("[]")${attrs ? " " + attrs : ""} // list as JSON text (was ${type}[])`;
    })
    .join("\n");
  return { schema: body, lists };
}

if (process.argv[1] && resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
  const { schema, lists } = toSqlite(readFileSync(BACKEND_SCHEMA, "utf8"));
  mkdirSync(dirname(out), { recursive: true });
  writeFileSync(out, `// Generated by scripts/full-schema.mjs from backend/prisma/schema.prisma. Do not edit.\n${schema}`);
  const { models, enums } = parseSchema(schema);
  console.log(`build/full/schema.prisma: ${models.size} models, ${enums.size} enums, ${lists} lists as JSON text`);
}
